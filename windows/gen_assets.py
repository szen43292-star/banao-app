# Turns ../www into assets.h (embedded files for the Windows launcher).
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'www')
MIME = {'.html':'text/html; charset=utf-8', '.css':'text/css; charset=utf-8', '.js':'text/javascript; charset=utf-8', '.woff2':'font/woff2', '.png':'image/png', '.json':'application/json', '.svg':'image/svg+xml', '.ico':'image/x-icon'}
files = []
for d, _, fs in os.walk(ROOT):
    for f in sorted(fs):
        full = os.path.join(d, f); rel = '/' + os.path.relpath(full, ROOT).replace(os.sep, '/')
        files.append((rel, MIME.get(os.path.splitext(f)[1], 'application/octet-stream'), open(full, 'rb').read()))
out = ['/* generated by gen_assets.py from ../www — do not edit */', '#pragma once', 'typedef struct { const char *path; const char *mime; const unsigned char *data; unsigned len; } asset_t;']
for i, (rel, mime, data) in enumerate(files):
    out.append('static const unsigned char A%d[] = {' % i)
    for k in range(0, len(data), 40):
        out.append(','.join(str(b) for b in data[k:k+40]) + ',')
    out.append('0};')
out.append('static const asset_t ASSETS[] = {')
for i, (rel, mime, data) in enumerate(files):
    out.append('  {"%s", "%s", A%d, %d},' % (rel, mime, i, len(data)))
out.append('};')
out.append('#define ASSET_COUNT %d' % len(files))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'assets.h'), 'w').write('\n'.join(out) + '\n')
print(len(files), 'files,', sum(len(f[2]) for f in files) // 1024, 'KB')
